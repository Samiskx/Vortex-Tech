-- =========================================================
-- VORTEX TECH — ESTRUTURA DO BANCO DE DADOS (PostgreSQL)
-- =========================================================
-- Execute com: npm run db:setup
-- (ou: psql -U postgres -d vortex_tech -f db/schema.sql)
-- =========================================================

-- ---------------------------------------------------------
-- 1. CATEGORIAS
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS categorias (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(60)  NOT NULL UNIQUE,
    slug        VARCHAR(60)  NOT NULL UNIQUE,
    descricao   TEXT,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- 2. PRODUTOS  (FK → categorias)
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS produtos (
    id            INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id  INTEGER       NOT NULL REFERENCES categorias (id) ON DELETE RESTRICT,
    nome          VARCHAR(120)  NOT NULL UNIQUE,
    descricao     TEXT          NOT NULL,
    preco         NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    estoque       INTEGER       NOT NULL DEFAULT 0 CHECK (estoque >= 0),
    imagem        VARCHAR(255),
    ativo         BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- 3. CLIENTES
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS clientes (
    id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(160) NOT NULL UNIQUE,
    telefone   VARCHAR(20),
    criado_em  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- 4. MENSAGENS / ATENDIMENTOS
--    FK → clientes  |  FK → produtos (opcional)
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS mensagens (
    id          INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  INTEGER     NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    produto_id  INTEGER     REFERENCES produtos (id) ON DELETE SET NULL,
    assunto     VARCHAR(160) NOT NULL,
    mensagem    TEXT        NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'novo'
                CHECK (status IN ('novo', 'em_atendimento', 'respondido')),
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- ÍNDICES
-- ---------------------------------------------------------
-- Todo PRIMARY KEY e UNIQUE já criam índice automaticamente.

-- Índice adicional justificado: a página de atendimentos lista as mensagens
-- mais recentes filtrando por status. Sem este índice o PostgreSQL precisa
-- ler a tabela inteira e ordenar tudo (Seq Scan + Sort). Com ele, faz uma
-- busca direta no índice já na ordem certa (Index Scan).
-- Demonstração completa em db/demo-indice.sql
CREATE INDEX IF NOT EXISTS idx_mensagens_status_criado
    ON mensagens (status, criado_em DESC);

-- Ajuda nos JOINs entre mensagens e clientes/produtos
CREATE INDEX IF NOT EXISTS idx_mensagens_cliente ON mensagens (cliente_id);
CREATE INDEX IF NOT EXISTS idx_produtos_categoria ON produtos (categoria_id);

-- ---------------------------------------------------------
-- COMENTÁRIOS (aparecem no \d+ e documentam o modelo)
-- ---------------------------------------------------------
COMMENT ON TABLE categorias IS 'Categorias do catálogo (smartphones, smartwatches, etc.)';
COMMENT ON TABLE produtos   IS 'Produtos vendidos pela Vortex Tech';
COMMENT ON TABLE clientes   IS 'Clientes que enviaram mensagens pelo site';
COMMENT ON TABLE mensagens  IS 'Mensagens/pedidos enviados pelo formulário de contato';
